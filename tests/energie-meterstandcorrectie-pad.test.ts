import assert from "node:assert/strict";
import { PGlite } from "@electric-sql/pglite";
import { readFileSync } from "node:fs";
import test from "node:test";
import { bouwEnergieMaandAnalyse } from "../src/lib/energie/maand-analyse";
import type { Brondata, EnergieMeterstand } from "../src/lib/energie/portfolio-analyse";

test("corrigeren via de RPC actualiseert beide buurintervallen en de gedeelde maanduitvoer", async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as
        $$ select '00000000-0000-0000-0000-000000000001'::uuid $$;
      create function public.mag_administratie_beheren() returns boolean
        language sql stable as $$ select true $$;
      create function public.mag_controles_uitvoeren() returns boolean
        language sql stable as $$ select false $$;
      create table public.meterstanden (
        id bigint primary key,
        woning_id bigint not null,
        opnamedatum date not null,
        controlesessie_id bigint,
        bewoners_aantal integer not null,
        dagstroom_kwh numeric,
        nachtstroom_kwh numeric,
        gas_m3 numeric,
        water_m3 numeric,
        opgenomen_door text,
        opmerkingen text,
        meteruitzonderingen jsonb not null default '{}',
        analyse_status text not null,
        analyse_resultaat jsonb not null,
        opvolging_nodig boolean not null,
        geanalyseerd_at timestamptz
      );
      create table public.meterstand_correcties (
        id bigint generated by default as identity primary key,
        meterstand_id bigint not null,
        woning_id bigint not null,
        controlesessie_id bigint,
        gecorrigeerd_door uuid,
        reden text not null,
        oude_waarden jsonb not null,
        nieuwe_waarden jsonb not null
      );
      insert into public.meterstanden (
        id, woning_id, opnamedatum, bewoners_aantal, dagstroom_kwh,
        analyse_status, analyse_resultaat, opvolging_nodig, geanalyseerd_at
      ) values
        (1, 16, '2026-10-01', 7, 1000, 'normaal', '{}', false, now()),
        (2, 16, '2026-10-11', 7, 1500, 'onwaarschijnlijk',
          '{"melding":"vervallen fout"}', true, now()),
        (3, 16, '2026-10-21', 7, 1220, 'normaal', '{}', false, now());
    `);
    const correctionMigration = readFileSync(
      "supabase/migrations/20260820150000_meterstandcorrectie_opgenomen_door.sql",
      "utf8",
    );
    await db.exec(correctionMigration);

    const { rows: corrected } = await db.query<{
      id: number;
      dagstroom_kwh: string;
      analyse_status: string;
      analyse_resultaat: Record<string, unknown>;
      opvolging_nodig: boolean;
      geanalyseerd_at: string | null;
    }>(
      `select * from public.corrigeer_meterstand(
        2, 7, 1100, null, null, null, 'Correcteur', 'Notitie',
        'Onjuiste tussenstand gecorrigeerd'
      )`,
    );
    assert.equal(corrected.length, 1);
    assert.equal(Number(corrected[0].dagstroom_kwh), 1100);
    assert.equal(corrected[0].analyse_status, "onvoldoende_data");
    assert.deepEqual(corrected[0].analyse_resultaat, {});
    assert.equal(corrected[0].opvolging_nodig, false);
    assert.equal(corrected[0].geanalyseerd_at, null);

    const { rows: audit } = await db.query<{
      oude_waarden: { dagstroom_kwh: number };
      nieuwe_waarden: { dagstroom_kwh: number };
    }>(
      `select oude_waarden, nieuwe_waarden
       from public.meterstand_correcties where meterstand_id = 2`,
    );
    assert.equal(audit.length, 1);
    assert.equal(audit[0].oude_waarden.dagstroom_kwh, 1500);
    assert.equal(audit[0].nieuwe_waarden.dagstroom_kwh, 1100);

    const { rows } = await db.query<{
      id: number;
      opnamedatum: string;
      dagstroom_kwh: string;
      bewoners_aantal: number;
      analyse_status: string;
      analyse_resultaat: Record<string, unknown>;
      opvolging_nodig: boolean;
    }>(
      `select id, opnamedatum::text as opnamedatum, dagstroom_kwh, bewoners_aantal,
              analyse_status, analyse_resultaat, opvolging_nodig
       from public.meterstanden order by opnamedatum`,
    );
    const readings: EnergieMeterstand[] = rows.map((row) => ({
      id: row.id,
      woning_id: 16,
      opnamedatum: row.opnamedatum,
      bewoners_aantal: row.bewoners_aantal,
      dagstroom_kwh: Number(row.dagstroom_kwh),
      nachtstroom_kwh: null,
      elektriciteit_kwh: null,
      gas_m3: null,
      water_m3: null,
      analyse_status: row.analyse_status,
      analyse_resultaat: row.analyse_resultaat,
      opvolging_nodig: row.opvolging_nodig,
    }));
    const source: Brondata = {
      woningen: [
        { id: 16, adres: "Testpand", postcode: "", plaats: "", status: "actief" },
      ],
      bedrijven: [{ id: 4, naam: "Testklant" }],
      verhuurperioden: [
        { id: 12, woning_id: 16, bedrijf_id: 4, startdatum: "2026-10-01" },
      ],
      bewoners: Array.from({ length: 7 }, (_, index) => ({
        id: index + 1,
        verhuurperiode_id: 12,
        incheckdatum: "2026-10-01",
        uitcheckdatum: null,
      })),
      meterstanden: readings,
      meterconfiguraties: [
        {
          woning_id: 16,
          product: "elektriciteit",
          meteridentiteit: "enkele-meter",
          registertype: "enkel",
          vanaf: "2026-10-01",
          tot: null,
        },
      ],
    };
    const report = bouwEnergieMaandAnalyse(
      source,
      [],
      {
        maanden: ["2026-10"],
        referentiemaand: "2026-10",
        drager: "elektriciteit",
        bedrijfIds: [4],
        woningIds: [16],
        maat: "verbruik",
        aggregatie: "pand",
      },
      "2026-10-31",
    );
    const january = report.woningen[0].maanden[0];
    assert.deepEqual(
      january.periodes
        .filter((period) => period.rekenwijze === "gemeten")
        .map((period) => period.verbruik),
      [100, 120],
      JSON.stringify(january),
    );
    assert.equal(january.periodes.some((period) => period.verbruik === 400), false);
    assert.equal(january.verbruik, 352);
    assert.equal(january.waarschuwingen.includes("vervallen fout"), false);
    assert.equal(january.status, "gedeeltelijk");
  } finally {
    await db.close();
  }
});
