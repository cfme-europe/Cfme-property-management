import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";
import { bepaalVoorgangers } from "../src/lib/meterstanden/voorganger";

const migratie = (naam: string) =>
  readFileSync(`supabase/migrations/${naam}`, "utf8");

type Rij = {
  id: number;
  opnamedatum: string;
  dagstroom_kwh: number | null;
  nachtstroom_kwh: number | null;
  gas_m3: number | null;
  water_m3: number | null;
};

test("foutieve opname → correctie → nieuwe controlesessie → juiste voorganger → vervolgopname geaccepteerd", async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as
        $$ select '00000000-0000-0000-0000-000000000001'::uuid $$;
      create function public.mag_administratie_beheren() returns boolean
        language sql stable as $$ select true $$;
      create function public.mag_controles_uitvoeren() returns boolean
        language sql stable as $$ select false $$;
      create table public.meterstanden (
        id bigint generated by default as identity primary key,
        woning_id bigint not null,
        opnamedatum date not null,
        controlesessie_id bigint,
        bewoners_aantal integer not null,
        dagstroom_kwh numeric, nachtstroom_kwh numeric, elektriciteit_kwh numeric,
        gas_m3 numeric, water_m3 numeric,
        opgenomen_door text, opmerkingen text,
        meteruitzonderingen jsonb not null default '{}',
        analyse_status text not null default 'onvoldoende_data',
        analyse_resultaat jsonb not null default '{}',
        opvolging_nodig boolean not null default false,
        geanalyseerd_at timestamptz
      );
      create table public.meterstand_correcties (
        id bigint generated by default as identity primary key,
        meterstand_id bigint not null, woning_id bigint not null,
        controlesessie_id bigint, gecorrigeerd_door uuid, reden text not null,
        oude_waarden jsonb not null, nieuwe_waarden jsonb not null
      );
    `);
    await db.exec(migratie("20260722224500_5_0f_dag_nachtstroom.sql").replace(/^alter table public\.meterstanden\s+add column[^;]*;/gim, ""));
    await db.exec(`
      create trigger meterstanden_oplopend_controleren
      before insert or update on public.meterstanden
      for each row execute function public.controleer_oplopende_meterstanden();
    `);
    await db.exec(migratie("20260820150000_meterstandcorrectie_opgenomen_door.sql"));

    // Sessie 1 (1 okt): goede opname. Sessie 2 (8 okt): typefout 5000 i.p.v. 1500.
    // Daarna (12 okt) een opname met alleen gas, zodat de laatste rij geen dagstand heeft.
    await db.exec(`
      insert into public.meterstanden (woning_id, opnamedatum, controlesessie_id, bewoners_aantal, dagstroom_kwh, gas_m3) values
        (16, '2026-10-01', 1, 7, 1000, 500),
        (16, '2026-10-08', 2, 7, 5000, null),
        (16, '2026-10-12', 3, 7, null, 520);
    `);

    const lees = async (): Promise<Rij[]> =>
      (
        await db.query<Record<string, string | number | null>>(
          `select id, opnamedatum::text as opnamedatum, dagstroom_kwh, nachtstroom_kwh, gas_m3, water_m3
           from public.meterstanden where woning_id = 16 order by opnamedatum desc`,
        )
      ).rows.map((r) => ({
        id: Number(r.id),
        opnamedatum: String(r.opnamedatum),
        dagstroom_kwh: r.dagstroom_kwh === null ? null : Number(r.dagstroom_kwh),
        nachtstroom_kwh: r.nachtstroom_kwh === null ? null : Number(r.nachtstroom_kwh),
        gas_m3: r.gas_m3 === null ? null : Number(r.gas_m3),
        water_m3: r.water_m3 === null ? null : Number(r.water_m3),
      }));

    // Oud gedrag: alleen de laatste rij → dagstand ontbreekt.
    const oudeVoorganger = (await lees())[0];
    assert.equal(oudeVoorganger.dagstroom_kwh, null);

    // Nieuwe sessie 4 vóór de correctie: voorganger is de foutieve stand, en de geldige vervolgopname wordt geweigerd.
    const voorCorrectie = bepaalVoorgangers(await lees(), "2026-10-20");
    assert.equal(voorCorrectie.dagstroom_kwh, 5000);
    assert.equal(voorCorrectie.gas_m3, 520);
    await assert.rejects(
      db.exec(`insert into public.meterstanden (woning_id, opnamedatum, controlesessie_id, bewoners_aantal, dagstroom_kwh)
               values (16, '2026-10-20', 4, 7, 1700)`),
      /mag niet lager zijn dan de vorige stand \(5000/,
    );

    // Correctie van de foutieve opname via de RPC.
    await db.query(
      `select * from public.corrigeer_meterstand(2, 7, 1500, null, null, null, 'Controleur', null, 'Typefout 5000 → 1500')`,
    );
    const { rows: audit } = await db.query<{ oude_waarden: { dagstroom_kwh: number }; nieuwe_waarden: { dagstroom_kwh: number } }>(
      `select oude_waarden, nieuwe_waarden from public.meterstand_correcties where meterstand_id = 2`,
    );
    assert.equal(audit[0].oude_waarden.dagstroom_kwh, 5000);
    assert.equal(audit[0].nieuwe_waarden.dagstroom_kwh, 1500);

    // Nieuwe controlesessie 5: gecorrigeerde voorganger per register.
    const naCorrectie = bepaalVoorgangers(await lees(), "2026-10-20");
    assert.equal(naCorrectie.dagstroom_kwh, 1500);
    assert.equal(naCorrectie.gas_m3, 520);
    assert.equal(naCorrectie.nachtstroom_kwh, null);

    // Een stand lager dan de gecorrigeerde voorganger blijft terecht geweigerd.
    await assert.rejects(
      db.exec(`insert into public.meterstanden (woning_id, opnamedatum, controlesessie_id, bewoners_aantal, dagstroom_kwh)
               values (16, '2026-10-20', 5, 7, 1400)`),
      /mag niet lager zijn dan de vorige stand \(1500/,
    );

    // Geldige vervolgopname op basis van de gecorrigeerde voorganger wordt geaccepteerd.
    await db.exec(`insert into public.meterstanden (woning_id, opnamedatum, controlesessie_id, bewoners_aantal, dagstroom_kwh, gas_m3)
                   values (16, '2026-10-20', 5, 7, 1700, 540)`);
    const { rows: opgeslagen } = await db.query<{ dagstroom_kwh: string; gas_m3: string }>(
      `select dagstroom_kwh, gas_m3 from public.meterstanden where opnamedatum = '2026-10-20'`,
    );
    assert.equal(Number(opgeslagen[0].dagstroom_kwh), 1700);
    assert.equal(Number(opgeslagen[0].gas_m3), 540);
  } finally {
    await db.close();
  }
});

test("voorganger sluit opnames op of na de opnamedatum uit en kiest deterministisch", () => {
  const rij = (id: number, d: string, dag: number | null): Rij => ({
    id, opnamedatum: d, dagstroom_kwh: dag, nachtstroom_kwh: null, gas_m3: null, water_m3: null,
  });
  const v = bepaalVoorgangers(
    [rij(1, "2026-10-01", 100), rij(2, "2026-10-05", 110), rij(3, "2026-10-05", 120), rij(4, "2026-10-20", 999), rij(5, "2026-10-25", 1999)],
    "2026-10-20",
  );
  assert.equal(v.dagstroom_kwh, 120);
});

