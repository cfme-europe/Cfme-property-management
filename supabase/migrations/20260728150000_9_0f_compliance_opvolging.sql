create or replace view
  public.compliance_werkpunten_overzicht
with (security_invoker = true)
as
select
  werkpunt.id,
  werkpunt.created_at,
  werkpunt.updated_at,
  werkpunt.woning_id,
  werkpunt.object_id,
  object.ruimte_id,
  ruimte.naam as ruimte_naam,
  object.object_type,
  object.naam as object_naam,
  object.objectnummer,
  werkpunt.verplichting_id,
  verplichting.naam as verplichting_naam,
  verplichting.verplichting_type,
  verplichting.certificering_type,
  verplichting.document_type,
  werkpunt.titel,
  werkpunt.omschrijving,
  werkpunt.bron_status,
  werkpunt.prioriteit,
  werkpunt.status,
  werkpunt.deadline,
  werkpunt.opgelost_op,
  werkpunt.genegeerd_op,
  taak.id as taak_id,
  taak.status as taak_status,
  taak.deadline as taak_deadline
from public.compliance_werkpunten werkpunt
join public.woning_objecten object
  on object.id = werkpunt.object_id
join public.woning_ruimten ruimte
  on ruimte.id = object.ruimte_id
join public.objecttype_compliance_verplichtingen
  verplichting
  on verplichting.id = werkpunt.verplichting_id
left join lateral (
  select taak.*
  from public.taken taak
  where taak.compliance_werkpunt_id = werkpunt.id
  order by
    (
      taak.status in (
        'open',
        'in_behandeling'
      )
    ) desc,
    taak.id desc
  limit 1
) taak on true;


