-- 4. AUTOMATISCHE SYNCHRONISATIE
-- =========================================================

create or replace function
  public.synchroniseer_compliance_voor_woning(
    p_woning_id bigint
  )
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  nieuwe_werkpunten integer := 0;
  bijgewerkte_werkpunten integer := 0;
  opgeloste_werkpunten integer := 0;
  nieuwe_taken integer := 0;
  afgeronde_taken integer := 0;
begin
  if p_woning_id is null or p_woning_id <= 0 then
    raise exception 'Ongeldige woning.';
  end if;

  with kandidaten as (
    select
      overzicht.woning_id,
      overzicht.object_id,
      overzicht.verplichting_id,
      overzicht.object_naam,
      overzicht.verplichting_naam,
      overzicht.verplichting_type,
      overzicht.compliance_status,
      overzicht.geldig_tot,
      case
        when overzicht.compliance_status = 'verlopen'
          then 'hoog'
        when overzicht.compliance_status = 'ontbreekt'
          then 'hoog'
        when overzicht.compliance_status = 'onvolledig'
          then 'normaal'
        else 'normaal'
      end as prioriteit,
      case
        when overzicht.compliance_status in (
          'verlopen',
          'ontbreekt'
        )
          then current_date + 7
        when overzicht.geldig_tot is not null
          then overzicht.geldig_tot
        else current_date + 30
      end as deadline
    from public.object_compliance_overzicht overzicht
    where overzicht.woning_id = p_woning_id
      and overzicht.compliance_status in (
        'waarschuwing',
        'verlopen',
        'ontbreekt',
        'onvolledig'
      )
  ),
  ingevoegd as (
    insert into public.compliance_werkpunten (
      woning_id,
      object_id,
      verplichting_id,
      titel,
      omschrijving,
      bron_status,
      prioriteit,
      status,
      deadline
    )
    select
      kandidaat.woning_id,
      kandidaat.object_id,
      kandidaat.verplichting_id,
      kandidaat.verplichting_naam
        || ' — '
        || kandidaat.object_naam,
      'Automatisch compliancewerkpunt voor '
        || kandidaat.verplichting_type
        || '. Actuele status: '
        || kandidaat.compliance_status
        || '.',
      kandidaat.compliance_status,
      kandidaat.prioriteit,
      'open',
      kandidaat.deadline
    from kandidaten kandidaat
    where not exists (
      select 1
      from public.compliance_werkpunten werkpunt
      where werkpunt.object_id = kandidaat.object_id
        and werkpunt.verplichting_id =
          kandidaat.verplichting_id
        and werkpunt.status = 'open'
    )
    returning id
  )
  select count(*)::integer
  into nieuwe_werkpunten
  from ingevoegd;

  with bijgewerkt as (
    update public.compliance_werkpunten werkpunt
    set
      bron_status = overzicht.compliance_status,
      prioriteit = case
        when overzicht.compliance_status in (
          'verlopen',
          'ontbreekt'
        )
          then 'hoog'
        else 'normaal'
      end,
      deadline = case
        when overzicht.compliance_status in (
          'verlopen',
          'ontbreekt'
        )
          then current_date + 7
        when overzicht.geldig_tot is not null
          then overzicht.geldig_tot
        else current_date + 30
      end,
      updated_at = now()
    from public.object_compliance_overzicht overzicht
    where werkpunt.woning_id = p_woning_id
      and werkpunt.status = 'open'
      and overzicht.object_id = werkpunt.object_id
      and overzicht.verplichting_id =
        werkpunt.verplichting_id
      and overzicht.compliance_status in (
        'waarschuwing',
        'verlopen',
        'ontbreekt',
        'onvolledig'
      )
    returning werkpunt.id
  )
  select count(*)::integer
  into bijgewerkte_werkpunten
  from bijgewerkt;

  with opgelost as (
    update public.compliance_werkpunten werkpunt
    set
      status = 'opgelost',
      opgelost_op = now(),
      updated_at = now()
    where werkpunt.woning_id = p_woning_id
      and werkpunt.status = 'open'
      and not exists (
        select 1
        from public.object_compliance_overzicht overzicht
        where overzicht.object_id = werkpunt.object_id
          and overzicht.verplichting_id =
            werkpunt.verplichting_id
          and overzicht.compliance_status in (
            'waarschuwing',
            'verlopen',
            'ontbreekt',
            'onvolledig'
          )
      )
    returning werkpunt.id
  )
  select count(*)::integer
  into opgeloste_werkpunten
  from opgelost;

  with afgerond as (
    update public.taken taak
    set
      status = 'afgerond',
      afgerond_op = current_date,
      updated_at = now()
    from public.compliance_werkpunten werkpunt
    where taak.compliance_werkpunt_id = werkpunt.id
      and taak.woning_id = p_woning_id
      and taak.status in (
        'open',
        'in_behandeling'
      )
      and werkpunt.status = 'opgelost'
    returning taak.id
  )
  select count(*)::integer
  into afgeronde_taken
  from afgerond;

  with ingevoegd as (
    insert into public.taken (
      woning_id,
      object_id,
      compliance_werkpunt_id,
      titel,
      omschrijving,
      categorie,
      prioriteit,
      status,
      startdatum,
      deadline,
      externe_referentie,
      opmerkingen
    )
    select
      werkpunt.woning_id,
      werkpunt.object_id,
      werkpunt.id,
      werkpunt.titel,
      werkpunt.omschrijving,
      case
        when verplichting.verplichting_type =
          'certificering'
          then 'veiligheid'
        else 'administratie'
      end,
      werkpunt.prioriteit,
      'open',
      current_date,
      werkpunt.deadline,
      'COMPLIANCE-WERKPUNT-'
        || werkpunt.id::text,
      'Automatisch aangemaakt door Compliance Intelligence.'
    from public.compliance_werkpunten werkpunt
    join public.objecttype_compliance_verplichtingen
      verplichting
      on verplichting.id = werkpunt.verplichting_id
    where werkpunt.woning_id = p_woning_id
      and werkpunt.status = 'open'
      and not exists (
        select 1
        from public.taken taak
        where taak.compliance_werkpunt_id =
          werkpunt.id
          and taak.status in (
            'open',
            'in_behandeling'
          )
      )
    returning id
  )
  select count(*)::integer
  into nieuwe_taken
  from ingevoegd;

  return jsonb_build_object(
    'woning_id', p_woning_id,
    'nieuwe_werkpunten', nieuwe_werkpunten,
    'bijgewerkte_werkpunten',
      bijgewerkte_werkpunten,
    'opgeloste_werkpunten',
      opgeloste_werkpunten,
    'nieuwe_taken', nieuwe_taken,
    'afgeronde_taken', afgeronde_taken
  );
end;
$$;


-- =========================================================
-- 5. SYNCHRONISATIE BIJ WIJZIGINGEN
-- =========================================================

create or replace function
  public.trigger_synchroniseer_compliance_woning()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  doel_woning_id bigint;
begin
  doel_woning_id := coalesce(
    new.woning_id,
    old.woning_id
  );

  if doel_woning_id is not null then
    perform public.synchroniseer_compliance_voor_woning(
      doel_woning_id
    );
  end if;

  return coalesce(new, old);
end;
$$;

drop trigger if exists
  certificeringen_compliance_synchronisatie
on public.certificeringen;

create trigger certificeringen_compliance_synchronisatie
after insert or update or delete
on public.certificeringen
for each row
execute function
  public.trigger_synchroniseer_compliance_woning();

drop trigger if exists
  documenten_compliance_synchronisatie
on public.documenten;

create trigger documenten_compliance_synchronisatie
after insert or update or delete
on public.documenten
for each row
execute function
  public.trigger_synchroniseer_compliance_woning();


create or replace function
  public.trigger_synchroniseer_objecttype_compliance()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  doel_object_type text;
  woning record;
begin
  doel_object_type := coalesce(
    new.object_type,
    old.object_type
  );

  for woning in
    select distinct object.woning_id
    from public.woning_objecten object
    where object.object_type = doel_object_type
  loop
    perform public.synchroniseer_compliance_voor_woning(
      woning.woning_id
    );
  end loop;

  return coalesce(new, old);
end;
$$;

drop trigger if exists
  objecttype_compliance_synchronisatie
on public.objecttype_compliance_verplichtingen;

create trigger objecttype_compliance_synchronisatie
after insert or update or delete
on public.objecttype_compliance_verplichtingen
for each row
execute function
  public.trigger_synchroniseer_objecttype_compliance();


