-- =========================================================
-- 1. COMPLIANCEWERKPUNTEN
-- =========================================================

create table if not exists public.compliance_werkpunten (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  woning_id bigint not null
    references public.woningen(id)
    on update cascade
    on delete restrict,

  object_id bigint not null
    references public.woning_objecten(id)
    on update cascade
    on delete restrict,

  verplichting_id bigint not null
    references public.objecttype_compliance_verplichtingen(id)
    on update cascade
    on delete restrict,

  titel text not null,
  omschrijving text,

  bron_status text not null
    check (
      bron_status in (
        'waarschuwing',
        'verlopen',
        'ontbreekt',
        'onvolledig'
      )
    ),

  prioriteit text not null default 'normaal'
    check (
      prioriteit in (
        'laag',
        'normaal',
        'hoog',
        'spoed'
      )
    ),

  status text not null default 'open'
    check (
      status in (
        'open',
        'opgelost',
        'genegeerd'
      )
    ),

  deadline date,
  opgelost_op timestamptz,
  genegeerd_op timestamptz,
  opmerkingen text,

  constraint compliance_werkpunten_titel_niet_leeg
    check (length(trim(titel)) > 0),

  constraint compliance_werkpunten_status_consistent
    check (
      (
        status = 'open'
        and opgelost_op is null
        and genegeerd_op is null
      )
      or
      (
        status = 'opgelost'
        and opgelost_op is not null
        and genegeerd_op is null
      )
      or
      (
        status = 'genegeerd'
        and genegeerd_op is not null
        and opgelost_op is null
      )
    )
);

create unique index if not exists
  compliance_werkpunten_open_uniek_idx
on public.compliance_werkpunten (
  object_id,
  verplichting_id
)
where status = 'open';

create index if not exists
  compliance_werkpunten_woning_idx
on public.compliance_werkpunten (
  woning_id,
  status,
  deadline
);

create index if not exists
  compliance_werkpunten_object_idx
on public.compliance_werkpunten(object_id);

create index if not exists
  compliance_werkpunten_verplichting_idx
on public.compliance_werkpunten(verplichting_id);


