create or replace function
  public.bewaak_compliance_werkpunt_integriteit()
returns trigger
language plpgsql
as $$
declare
  object_woning_id bigint;
  verplichting_object_type text;
  object_object_type text;
begin
  select woning_id, object_type
  into object_woning_id, object_object_type
  from public.woning_objecten
  where id = new.object_id;

  if object_woning_id is null then
    raise exception 'Complianceobject bestaat niet.';
  end if;

  if object_woning_id <> new.woning_id then
    raise exception
      'Compliancewerkpunt en object moeten bij dezelfde woning horen.';
  end if;

  select object_type
  into verplichting_object_type
  from public.objecttype_compliance_verplichtingen
  where id = new.verplichting_id;

  if verplichting_object_type is null then
    raise exception 'Complianceverplichting bestaat niet.';
  end if;

  if verplichting_object_type <> object_object_type then
    raise exception
      'Complianceverplichting past niet bij het objecttype.';
  end if;

  new.updated_at = now();

  if new.status = 'opgelost'
     and new.opgelost_op is null then
    new.opgelost_op = now();
  end if;

  if new.status = 'genegeerd'
     and new.genegeerd_op is null then
    new.genegeerd_op = now();
  end if;

  if new.status = 'open' then
    new.opgelost_op = null;
    new.genegeerd_op = null;
  end if;

  return new;
end;
$$;

drop trigger if exists
  compliance_werkpunten_integriteit
on public.compliance_werkpunten;

create trigger compliance_werkpunten_integriteit
before insert or update
on public.compliance_werkpunten
for each row
execute function
  public.bewaak_compliance_werkpunt_integriteit();


create or replace function
  public.bewaak_taak_compliance_integriteit()
returns trigger
language plpgsql
as $$
declare
  object_woning_id bigint;
  werkpunt_woning_id bigint;
  werkpunt_object_id bigint;
begin
  if new.object_id is not null then
    select woning_id
    into object_woning_id
    from public.woning_objecten
    where id = new.object_id;

    if object_woning_id is null then
      raise exception 'Taakobject bestaat niet.';
    end if;

    if object_woning_id <> new.woning_id then
      raise exception
        'Taak en object moeten bij dezelfde woning horen.';
    end if;
  end if;

  if new.compliance_werkpunt_id is not null then
    select woning_id, object_id
    into werkpunt_woning_id, werkpunt_object_id
    from public.compliance_werkpunten
    where id = new.compliance_werkpunt_id;

    if werkpunt_woning_id is null then
      raise exception 'Compliancewerkpunt bestaat niet.';
    end if;

    if werkpunt_woning_id <> new.woning_id then
      raise exception
        'Taak en compliancewerkpunt moeten bij dezelfde woning horen.';
    end if;

    if new.object_id is null then
      new.object_id = werkpunt_object_id;
    elsif new.object_id <> werkpunt_object_id then
      raise exception
        'Taakobject wijkt af van het compliancewerkpunt.';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists
  taken_compliance_integriteit
on public.taken;

create trigger taken_compliance_integriteit
before insert or update of
  woning_id,
  object_id,
  compliance_werkpunt_id
on public.taken
for each row
execute function
  public.bewaak_taak_compliance_integriteit();


