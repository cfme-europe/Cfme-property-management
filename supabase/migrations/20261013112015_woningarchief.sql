begin;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated;

alter table public.woningen
  add column if not exists status text not null default 'actief',
  add column if not exists gearchiveerd_op timestamptz,
  add column if not exists archiefreden text,
  add column if not exists gearchiveerd_door uuid references auth.users(id),
  add column if not exists gearchiveerd_door_naam text;

alter table public.woningen
  drop constraint if exists woningen_status_geldig;

alter table public.woningen
  add constraint woningen_status_geldig
  check (status in ('actief', 'gearchiveerd'));

alter table public.woningen
  drop constraint if exists woningen_archivering_consistent;

alter table public.woningen
  add constraint woningen_archivering_consistent
  check (
    (
      status = 'actief'
      and gearchiveerd_op is null
      and archiefreden is null
      and gearchiveerd_door is null
      and gearchiveerd_door_naam is null
    )
    or
    (
      status = 'gearchiveerd'
      and gearchiveerd_op is not null
      and archiefreden is not null
      and length(trim(archiefreden)) between 5 and 1000
      and gearchiveerd_door is not null
      and gearchiveerd_door_naam is not null
      and length(trim(gearchiveerd_door_naam)) > 0
    )
  );

create index if not exists woningen_status_idx
on public.woningen(status);

create table if not exists public.woning_statushistorie (
  id bigint generated by default as identity primary key,
  woning_id bigint not null references public.woningen(id) on delete restrict,
  vorige_status text not null check (vorige_status in ('actief', 'gearchiveerd')),
  nieuwe_status text not null check (nieuwe_status in ('actief', 'gearchiveerd')),
  reden text not null check (length(trim(reden)) between 5 and 1000),
  gewijzigd_op timestamptz not null default now(),
  gewijzigd_door uuid not null references auth.users(id),
  gewijzigd_door_naam text not null check (length(trim(gewijzigd_door_naam)) > 0),
  constraint woning_statushistorie_statuswijziging
    check (vorige_status <> nieuwe_status)
);

create index if not exists woning_statushistorie_woning_idx
on public.woning_statushistorie(woning_id, gewijzigd_op desc);

alter table public.woning_statushistorie enable row level security;

drop policy if exists "woningstatushistorie bekijken"
on public.woning_statushistorie;

create policy "woningstatushistorie bekijken"
on public.woning_statushistorie
for select
to authenticated
using ((select auth.uid()) is not null);

revoke all on public.woning_statushistorie from anon;
revoke all on public.woning_statushistorie from authenticated;
grant select on public.woning_statushistorie to authenticated;

create or replace function private.archiveer_woning(
  p_woning_id bigint,
  p_reden text
)
returns public.woningen
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_woning public.woningen;
  v_reden text := trim(coalesce(p_reden, ''));
  v_gebruiker_id uuid := auth.uid();
  v_gebruiker_naam text;
begin
  if v_gebruiker_id is null or not public.mag_wijzigen() then
    raise exception 'Onvoldoende rechten om een woning te archiveren.';
  end if;

  if p_woning_id is null or p_woning_id <= 0 then
    raise exception 'Ongeldige woning.';
  end if;

  if length(v_reden) < 5 or length(v_reden) > 1000 then
    raise exception 'De archiefreden moet tussen 5 en 1000 tekens bevatten.';
  end if;

  select *
  into v_woning
  from public.woningen
  where id = p_woning_id
  for update;

  if v_woning.id is null then
    raise exception 'Woning niet gevonden.';
  end if;

  if v_woning.status = 'gearchiveerd' then
    raise exception 'Deze woning is al gearchiveerd.';
  end if;

  if exists (
    select 1
    from public.verhuurperiodes
    where woning_id = p_woning_id
      and status = 'actief'
  ) then
    raise exception 'Beëindig eerst de actieve verhuurperiode.';
  end if;

  if exists (
    select 1
    from public.controlesessies
    where woning_id = p_woning_id
      and status = 'bezig'
  ) then
    raise exception 'Rond eerst de actieve controle af of annuleer deze.';
  end if;

  select coalesce(
    nullif(trim(volledige_naam), ''),
    nullif(trim(email), ''),
    'Onbekende gebruiker'
  )
  into v_gebruiker_naam
  from public.profiles
  where id = v_gebruiker_id;

  v_gebruiker_naam := coalesce(v_gebruiker_naam, 'Onbekende gebruiker');

  update public.woning_rayon_toewijzingen
  set
    actief = false,
    geldig_tot = coalesce(geldig_tot, greatest(current_date, geldig_vanaf)),
    reden = concat_ws(
      E'\n',
      nullif(trim(coalesce(reden, '')), ''),
      'Woning gearchiveerd: ' || v_reden
    )
  where woning_id = p_woning_id
    and actief = true;

  update public.taken
  set
    status = 'geannuleerd',
    opmerkingen = concat_ws(
      E'\n',
      nullif(trim(coalesce(opmerkingen, '')), ''),
      '[' || to_char(now(), 'DD-MM-YYYY HH24:MI') ||
        '] Geannuleerd bij woningarchivering door ' ||
        v_gebruiker_naam || ': ' || v_reden
    )
  where woning_id = p_woning_id
    and status in ('open', 'in_behandeling');

  update public.intelligence_werkpunten
  set
    status = 'vervallen',
    afgehandeld_at = now(),
    afgehandeld_door = v_gebruiker_id,
    afgehandeld_door_naam = v_gebruiker_naam,
    afhandelnotitie = concat_ws(
      E'\n',
      nullif(trim(coalesce(afhandelnotitie, '')), ''),
      'Woning gearchiveerd: ' || v_reden
    )
  where woning_id = p_woning_id
    and status in ('concept', 'actief');

  update public.woningen
  set
    status = 'gearchiveerd',
    gearchiveerd_op = now(),
    archiefreden = v_reden,
    gearchiveerd_door = v_gebruiker_id,
    gearchiveerd_door_naam = v_gebruiker_naam
  where id = p_woning_id
  returning * into v_woning;

  insert into public.woning_statushistorie (
    woning_id,
    vorige_status,
    nieuwe_status,
    reden,
    gewijzigd_door,
    gewijzigd_door_naam
  ) values (
    p_woning_id,
    'actief',
    'gearchiveerd',
    v_reden,
    v_gebruiker_id,
    v_gebruiker_naam
  );

  return v_woning;
end;
$$;

