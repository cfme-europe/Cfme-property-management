create or replace function private.bewaar_woningarchief_via_rpc()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if current_user in ('anon', 'authenticated') then
    if tg_op = 'INSERT' then
      if new.status is distinct from 'actief'
        or new.gearchiveerd_op is not null
        or new.archiefreden is not null
        or new.gearchiveerd_door is not null
        or new.gearchiveerd_door_naam is not null then
        raise exception 'Gebruik de woningarchiefactie voor archiefvelden.';
      end if;
    elsif row(
      new.status,
      new.gearchiveerd_op,
      new.archiefreden,
      new.gearchiveerd_door,
      new.gearchiveerd_door_naam
    ) is distinct from row(
      old.status,
      old.gearchiveerd_op,
      old.archiefreden,
      old.gearchiveerd_door,
      old.gearchiveerd_door_naam
    ) then
      raise exception 'Gebruik de woningarchiefactie voor archiefvelden.';
    end if;
  end if;

  return new;
end;
$$;

revoke all on function private.bewaar_woningarchief_via_rpc() from public, anon, authenticated;
drop trigger if exists woningen_archief_via_rpc on public.woningen;
create trigger woningen_archief_via_rpc
before insert or update on public.woningen
for each row execute function private.bewaar_woningarchief_via_rpc();

create or replace view public.woning_planning_intelligence
with (security_invoker = true)
as
with laatste_controle as (
  select distinct on (historie.woning_id)
    historie.woning_id,
    historie.controleur_id,
    historie.controlemoment
  from public.planning_controlehistorie historie
  where historie.controlemoment is not null
    and historie.status not in (
      'concept',
      'geannuleerd',
      'annulering',
      'open'
    )
  order by historie.woning_id, historie.controlemoment desc
),
actieve_toewijzing as (
  select
    toewijzing.id as toewijzing_id,
    toewijzing.woning_id,
    toewijzing.rayon_id,
    rayon.naam as rayon_naam,
    rayon.code as rayon_code,
    coalesce(
      toewijzing.standaard_controleur_id,
      rayon.standaard_controleur_id
    ) as controleur_id,
    coalesce(
      toewijzing.controlefrequentie_dagen,
      rayon.standaard_controlefrequentie_dagen
    ) as controlefrequentie_dagen,
    toewijzing.geldig_vanaf
  from public.woning_rayon_toewijzingen toewijzing
  join public.rayons rayon on rayon.id = toewijzing.rayon_id
  where toewijzing.actief = true
    and toewijzing.geldig_tot is null
    and rayon.actief = true
)
select
  woning.id as woning_id,
  woning.adres,
  woning.postcode,
  woning.plaats,
  planning.toewijzing_id,
  planning.rayon_id,
  planning.rayon_naam,
  planning.rayon_code,
  planning.controleur_id,
  profiel.volledige_naam as controleur_naam,
  profiel.email as controleur_email,
  planning.controlefrequentie_dagen,
  planning.geldig_vanaf,
  laatste.controlemoment::date as laatste_controle_op,
  case
    when planning.toewijzing_id is null then null
    when laatste.controlemoment is null then planning.geldig_vanaf
    else laatste.controlemoment::date + planning.controlefrequentie_dagen
  end as volgende_controle_op,
  case
    when planning.toewijzing_id is null then null
    when laatste.controlemoment is null then planning.geldig_vanaf - current_date
    else laatste.controlemoment::date + planning.controlefrequentie_dagen - current_date
  end as dagen_tot_controle,
  case
    when planning.toewijzing_id is null then 'niet_ingepland'
    when planning.controleur_id is null then 'geen_controleur'
    when (
      case
        when laatste.controlemoment is null then planning.geldig_vanaf
        else laatste.controlemoment::date + planning.controlefrequentie_dagen
      end
    ) < current_date then 'achterstallig'
    when (
      case
        when laatste.controlemoment is null then planning.geldig_vanaf
        else laatste.controlemoment::date + planning.controlefrequentie_dagen
      end
    ) = current_date then 'vandaag'
    when (
      case
        when laatste.controlemoment is null then planning.geldig_vanaf
        else laatste.controlemoment::date + planning.controlefrequentie_dagen
      end
    ) <= current_date + 7 then 'binnen_7_dagen'
    when (
      case
        when laatste.controlemoment is null then planning.geldig_vanaf
        else laatste.controlemoment::date + planning.controlefrequentie_dagen
      end
    ) <= current_date + 14 then 'binnen_14_dagen'
    else 'op_schema'
  end as planning_status,
  case
    when planning.toewijzing_id is null then 1
    when planning.controleur_id is null then 2
    when (
      case
        when laatste.controlemoment is null then planning.geldig_vanaf
        else laatste.controlemoment::date + planning.controlefrequentie_dagen
      end
    ) < current_date then 3
    when (
      case
        when laatste.controlemoment is null then planning.geldig_vanaf
        else laatste.controlemoment::date + planning.controlefrequentie_dagen
      end
    ) = current_date then 4
    when (
      case
        when laatste.controlemoment is null then planning.geldig_vanaf
        else laatste.controlemoment::date + planning.controlefrequentie_dagen
      end
    ) <= current_date + 7 then 5
    when (
      case
        when laatste.controlemoment is null then planning.geldig_vanaf
        else laatste.controlemoment::date + planning.controlefrequentie_dagen
      end
    ) <= current_date + 14 then 6
    else 7
  end as planning_prioriteit
from public.woningen woning
left join actieve_toewijzing planning on planning.woning_id = woning.id
left join laatste_controle laatste on laatste.woning_id = woning.id
left join public.profiles profiel on profiel.id = planning.controleur_id
where woning.status = 'actief';

commit;
