-- 2. DOCUMENTEN OP OBJECTNIVEAU
-- =========================================================

alter table public.documenten
add column if not exists object_id bigint;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'documenten_object_id_fkey'
      and conrelid = 'public.documenten'::regclass
  ) then
    alter table public.documenten
    add constraint documenten_object_id_fkey
    foreign key (object_id)
    references public.woning_objecten(id)
    on update cascade
    on delete restrict;
  end if;
end;
$$;

create index if not exists
  documenten_object_id_idx
on public.documenten(object_id);

create or replace function
  public.bewaak_document_object_integriteit()
returns trigger
language plpgsql
as $$
declare
  object_woning_id bigint;
begin
  if new.object_id is null then
    return new;
  end if;

  select woning_id
  into object_woning_id
  from public.woning_objecten
  where id = new.object_id;

  if object_woning_id is null then
    raise exception 'Object bestaat niet.';
  end if;

  if object_woning_id <> new.woning_id then
    raise exception
      'Document en object moeten bij dezelfde woning horen.';
  end if;

  return new;
end;
$$;

drop trigger if exists
  documenten_object_integriteit
on public.documenten;

create trigger documenten_object_integriteit
before insert or update of woning_id, object_id
on public.documenten
for each row
execute function public.bewaak_document_object_integriteit();


