-- =========================================================
-- 1. COMPLIANCEVERPLICHTINGEN PER OBJECTTYPE
-- =========================================================

create table if not exists public.objecttype_compliance_verplichtingen (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  object_type text not null,
  naam text not null,
  omschrijving text,

  verplichting_type text not null
    check (
      verplichting_type in (
        'certificering',
        'document'
      )
    ),

  certificering_type text
    check (
      certificering_type is null
      or certificering_type in (
        'scope',
        'brandblusser',
        'cv',
        'rookmelder',
        'overig'
      )
    ),

  document_type text
    check (
      document_type is null
      or document_type in (
        'contract',
        'certificering',
        'keuring',
        'inspectie',
        'verzekering',
        'factuur',
        'rapportage',
        'handleiding',
        'identificatie',
        'overig'
      )
    ),

  waarschuwingsdagen integer not null default 30
    check (waarschuwingsdagen between 0 and 365),

  verplicht boolean not null default true,
  actief boolean not null default true,

  opmerkingen text,

  constraint objecttype_compliance_object_type_niet_leeg
    check (length(trim(object_type)) > 0),

  constraint objecttype_compliance_naam_niet_leeg
    check (length(trim(naam)) > 0),

  constraint objecttype_compliance_type_consistent
    check (
      (
        verplichting_type = 'certificering'
        and certificering_type is not null
        and document_type is null
      )
      or
      (
        verplichting_type = 'document'
        and document_type is not null
        and certificering_type is null
      )
    )
);

create unique index if not exists
  objecttype_compliance_certificering_uniek_idx
on public.objecttype_compliance_verplichtingen (
  object_type,
  certificering_type
)
where verplichting_type = 'certificering';

create unique index if not exists
  objecttype_compliance_document_uniek_idx
on public.objecttype_compliance_verplichtingen (
  object_type,
  document_type
)
where verplichting_type = 'document';

create index if not exists
  objecttype_compliance_object_type_idx
on public.objecttype_compliance_verplichtingen (
  object_type,
  actief,
  verplicht
);

create or replace function
  public.objecttype_compliance_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists
  objecttype_compliance_set_updated_at
on public.objecttype_compliance_verplichtingen;

create trigger objecttype_compliance_set_updated_at
before update
on public.objecttype_compliance_verplichtingen
for each row
execute function public.objecttype_compliance_set_updated_at();


