-- 3. DOCUMENTENOVERZICHT UITBREIDEN
-- =========================================================

create or replace view public.documenten_overzicht
with (security_invoker = true)
as
select
  document.id,
  document.created_at,
  document.updated_at,
  document.woning_id,
  document.titel,
  document.document_type,
  document.omschrijving,
  document.status,
  document.vertrouwelijkheid,
  document.gearchiveerd_op,
  document.archiefreden,
  document.aangemaakt_door,
  document.gewijzigd_door,
  laatste.id as laatste_versie_id,
  laatste.versienummer as laatste_versienummer,
  laatste.created_at as laatste_versie_created_at,
  laatste.bestandspad as laatste_bestandspad,
  laatste.bestandsnaam as laatste_bestandsnaam,
  laatste.mime_type as laatste_mime_type,
  laatste.bestandsgrootte as laatste_bestandsgrootte,
  laatste.versie_opmerking as laatste_versie_opmerking,
  coalesce(versies.aantal, 0)::integer as aantal_versies,
  document.object_id,
  object.naam as object_naam,
  object.object_type,
  object.objectnummer,
  object.ruimte_id,
  ruimte.naam as ruimte_naam
from public.documenten document
left join public.woning_objecten object
  on object.id = document.object_id
left join public.woning_ruimten ruimte
  on ruimte.id = object.ruimte_id
left join lateral (
  select versie.*
  from public.documentversies versie
  where versie.document_id = document.id
  order by versie.versienummer desc
  limit 1
) laatste on true
left join lateral (
  select count(*) as aantal
  from public.documentversies versie
  where versie.document_id = document.id
) versies on true;

-- =========================================================
-- 4. CERTIFICERINGENOVERZICHT UITBREIDEN
-- =========================================================

create or replace view public.certificeringen_overzicht
with (security_invoker = true)
as
select
  certificering.id,
  certificering.created_at,
  certificering.updated_at,
  certificering.woning_id,
  certificering.type,
  certificering.naam,
  certificering.installatie_omschrijving,
  certificering.certificaatnummer,
  certificering.keuringsinstantie,
  certificering.keuringsdatum,
  certificering.geldig_tot,
  certificering.waarschuwingsdagen,
  certificering.actief,
  certificering.ingetrokken_op,
  certificering.reden_inhouding,
  certificering.opmerkingen,
  certificering.aangemaakt_door,
  certificering.gewijzigd_door,
  case
    when certificering.actief = false
      then 'ingetrokken'
    when certificering.geldig_tot < current_date
      then 'verlopen'
    when certificering.geldig_tot
      <= current_date + certificering.waarschuwingsdagen
      then 'verloopt_binnenkort'
    else 'geldig'
  end as compliance_status,
  certificering.geldig_tot - current_date
    as resterende_dagen,
  certificering.object_id,
  object.naam as object_naam,
  object.object_type,
  object.objectnummer,
  object.ruimte_id,
  ruimte.naam as ruimte_naam
from public.certificeringen certificering
left join public.woning_objecten object
  on object.id = certificering.object_id
left join public.woning_ruimten ruimte
  on ruimte.id = object.ruimte_id;

-- =========================================================
-- 5. CENTRAAL OBJECTCOMPLIANCEOVERZICHT
-- =========================================================

create or replace view public.object_compliance_overzicht
with (security_invoker = true)
as
select
  object.id as object_id,
  object.woning_id,
  object.ruimte_id,
  ruimte.naam as ruimte_naam,
  object.object_type,
  object.naam as object_naam,
  object.objectnummer,
  object.merk,
  object.model,
  object.serienummer,

  verplichting.id as verplichting_id,
  verplichting.naam as verplichting_naam,
  verplichting.omschrijving as verplichting_omschrijving,
  verplichting.verplichting_type,
  verplichting.certificering_type,
  verplichting.document_type,
  verplichting.waarschuwingsdagen,
  verplichting.verplicht,

  certificering.id as certificering_id,
  certificering.geldig_tot,
  certificering.actief as certificering_actief,
  certificering.compliance_status
    as certificering_status,

  document.id as document_id,
  document.status as document_status,
  document.laatste_versie_id,
  document.laatste_versie_created_at,

  case
    when verplichting.verplichting_type = 'certificering'
      and certificering.id is null
      then 'ontbreekt'

    when verplichting.verplichting_type = 'certificering'
      and certificering.compliance_status = 'verlopen'
      then 'verlopen'

    when verplichting.verplichting_type = 'certificering'
      and certificering.compliance_status = 'verloopt_binnenkort'
      then 'waarschuwing'

    when verplichting.verplichting_type = 'certificering'
      and certificering.compliance_status = 'ingetrokken'
      then 'ontbreekt'

    when verplichting.verplichting_type = 'certificering'
      and certificering.compliance_status = 'geldig'
      then 'compliant'

    when verplichting.verplichting_type = 'document'
      and document.id is null
      then 'ontbreekt'

    when verplichting.verplichting_type = 'document'
      and document.status = 'gearchiveerd'
      then 'ontbreekt'

    when verplichting.verplichting_type = 'document'
      and document.laatste_versie_id is null
      then 'onvolledig'

    when verplichting.verplichting_type = 'document'
      then 'compliant'

    else 'onbekend'
  end as compliance_status,

  case
    when verplichting.verplichting_type = 'certificering'
      then certificering.geldig_tot - current_date
    else null
  end as resterende_dagen

from public.woning_objecten object
join public.woning_ruimten ruimte
  on ruimte.id = object.ruimte_id
join public.objecttype_compliance_verplichtingen verplichting
  on verplichting.object_type = object.object_type
  and verplichting.actief = true
  and verplichting.verplicht = true

left join lateral (
  select overzicht.*
  from public.certificeringen_overzicht overzicht
  where overzicht.object_id = object.id
    and overzicht.type = verplichting.certificering_type
  order by
    overzicht.actief desc,
    overzicht.geldig_tot desc,
    overzicht.id desc
  limit 1
) certificering
  on verplichting.verplichting_type = 'certificering'

left join lateral (
  select overzicht.*
  from public.documenten_overzicht overzicht
  where overzicht.object_id = object.id
    and overzicht.document_type = verplichting.document_type
  order by
    (overzicht.status = 'actief') desc,
    overzicht.updated_at desc,
    overzicht.id desc
  limit 1
) document
  on verplichting.verplichting_type = 'document'

where object.actief = true;


-- =========================================================
-- 6. SAMENVATTING PER WONING
-- =========================================================

create or replace view public.woning_compliance_samenvatting
with (security_invoker = true)
as
select
  woning_id,
  count(*)::integer as aantal_verplichtingen,
  count(*) filter (
    where compliance_status = 'compliant'
  )::integer as compliant,
  count(*) filter (
    where compliance_status = 'waarschuwing'
  )::integer as waarschuwingen,
  count(*) filter (
    where compliance_status = 'verlopen'
  )::integer as verlopen,
  count(*) filter (
    where compliance_status in (
      'ontbreekt',
      'onvolledig'
    )
  )::integer as ontbrekend,
  case
    when count(*) filter (
      where compliance_status in (
        'verlopen',
        'ontbreekt',
        'onvolledig'
      )
    ) > 0 then 'niet_compliant'

    when count(*) filter (
      where compliance_status = 'waarschuwing'
    ) > 0 then 'aandacht'

    else 'compliant'
  end as compliance_status
from public.object_compliance_overzicht
group by woning_id;


